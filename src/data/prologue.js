// ---------- 序章的目标提示 ----------
export function prologueObjective(s) {
  const f = s.flags;
  if (!f.p_wake) return '';
  if (!f.p_tea) return '跟噪噪去公园西边的鹤鸣茶社听书';
  if (!prologueDone3(s)) {
    const left = [!f.p_magpie && '相亲角', !f.p_monument && '纪念碑', !f.maoda_p && '湖边'].filter(Boolean);
    return `在公园里逛逛（还剩：${left.join('、')}）`;
  }
  return '天快黑了，回家（东边的老银杏）';
}
