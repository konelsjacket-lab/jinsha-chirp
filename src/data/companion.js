const GENERIC = [
  '你头上的白毛，在雾里头还亮得很。',
  '饿了。你饿不饿？我带的瓜子吃完了。',
  '你说太阳神鸟当年要是打准了，现在来找神鸟的是不是就是凤凰了？',
  '巧克力～巧克力～……我学你学得像不像？',
];
let n = 0;

export function chatter(s, place) {
  // 地图名是“少城·宽窄巷子”这种，按包含的关键字找
  const key = Object.keys(LINES).find(k => place && place.includes(k));
  const pool = [...(key ? LINES[key] : []), ...GENERIC];
  const line = pool[n++ % pool.length];
  return say('噪噪', line);
}
