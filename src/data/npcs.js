// ---------- 诸葛先生的三道考题：答错了给提示再答，最多再答两回 ----------
const QUIZ = [
  {
    q: '第一问：盖碗茶的茶盖、茶碗、茶托，各代表啥子？',
    right: '盖是天，碗是人，托是地',
    wrong: ['盖是地，碗是天，托是人', '盖碗茶就是茶，不代表啥子'],
    hint: '鹤鸣茶社的龟大爷，一边倒茶一边讲过的。天在上，地在下，人在中间。',
  },
  {
    q: '第二问：宽窄巷子那一片，清朝的时候叫啥子？',
    right: '少城，也叫满城',
    wrong: ['龟城', '芙蓉城'],
    hint: '戴胜师傅的师父，就是那里头一位八旗老兵养的鸟。城中之城。',
  },
  {
    q: '第三问：太阳神鸟金箔上，绕着太阳飞的神鸟，一共几只？',
    right: '四只',
    wrong: ['十二只', '一只'],
    hint: '十二道是光，不是鸟。你头上那撮白毛，就是在找它们。',
  },
];

function quizStep(i, tries) {
  if (i >= QUIZ.length) return [];
  const q = QUIZ[i];
  const next = quizStep(i + 1, 2);
  const wrongThen = tries > 0
    ? [...say('诸葛先生', '（羽扇一顿）……非也，非也。', q.hint), ...quizStep(i, tries - 1)]
    : [...say('诸葛先生', `（叹气）罢了罢了，老夫直说：${q.right}。记住了哈。`), ...next];
  const opts = [
    { label: q.right, then: [...say('诸葛先生', '善！'), ...next] },
    ...q.wrong.map(w => ({ label: w, then: wrongThen })),
  ];
  // 正确答案的位置轮换一下，免得一直是第一个
  const k = i % opts.length;
  return [{ choice: q.q, who: '诸葛先生', options: [...opts.slice(k), ...opts.slice(0, k)] }];
}

// ---------- 芙蓉花精：全城三处芙蓉树，找齐了讲芙蓉城的故事 ----------
const FURONG_SPOTS = ['furong_a', 'furong_b', 'furong_c'];
const furongCount = s => FURONG_SPOTS.filter(k => s.flags[k]).length;
const FURONG_LINES = {
  furong_a: ['（巷口一朵大大的芙蓉花，慢慢转过来看着你）', '……早上是白的，中午是粉的，到了晚上是红的。', '所以他们喊我们“三醉芙蓉”。我现在是早上，还没醉。'],
  furong_b: ['（江边一朵芙蓉花打了个呵欠）', '锦江边的风好舒服……你在找我的姊妹？', '我们原来在城墙上排成一排，四十里长。现在散了，一棵一棵的。'],
  furong_c: ['（红墙边上一朵芙蓉，花瓣已经红透了）', '我晚上了。我醉了。', '你莫看我，我脸红。'],
};
function furong(id) {
  return {
    id, name: '芙蓉花精', sprite: 'npc_furong',
    when: s => s.flags.intro_done,
    script: s => {
      if (s.flags.furong_done) return say('芙蓉花精', '秋天再来看我们嘛。一整条街都是。');
      if (s.flags[id]) return say('芙蓉花精', `还有 ${3 - furongCount(s)} 棵芙蓉树等着你。宽窄巷子、廊桥边、武侯祠的红墙下面……`);
      const n = furongCount(s) + 1;
      const meet = [...say('芙蓉花精', ...FURONG_LINES[id]), { flag: id }];
      if (n < 3) return [...meet, ...say('', `（找到了 ${n} / 3 棵芙蓉树）`)];
      return [
        ...meet,
        ...say('芙蓉花精',
          '三棵都找到了？那给你讲个老故事。',
          '一千多年前，后蜀有个皇帝叫孟昶。他喜欢芙蓉，叫人在成都的城墙上种满了芙蓉树。',
          '一到秋天，四十里城墙全开了花，远远看过去，就像整座城铺了一层锦。',
          '从那以后，成都就叫“芙蓉城”，简称“蓉城”。'),
        ...say('白果:surprised', '原来“蓉”是你们的“蓉”！'),
        ...say('芙蓉花精', '现在我们也是成都的市花。这几滴花露你拿去，喝了精神。'),
        { give: 'furong', n: 2 },
        { codex: 'furong' },
        { flag: 'furong_done' },
      ];
    },
  };
}

